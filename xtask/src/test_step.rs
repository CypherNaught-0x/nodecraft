//! The test step of `cargo xtask ci`, in its full and `--quick` forms, and `cargo xtask slow-tests`,
//! which keeps the generated slow-test block of `.config/nextest.toml` current.
//!
//! Full runs every test. Quick runs only the packages a change can affect (those it touches and
//! everything that depends on them) and leaves out the tests listed as slow. Both compile exactly
//! what full does, `--workspace` with the same features, so switching between them never rebuilds
//! dependencies under a different feature set.

use std::collections::BTreeSet;
use std::path::Path;
use std::process::Command;

use crate::{PROVIDER_FEATURES, cargo, metadata, run};

const NEXTEST_CONFIG: &str = ".config/nextest.toml";
const BEGIN: &str = "# --- slow tests: generated by `cargo xtask slow-tests`; do not edit by hand ---";
const END: &str = "# --- end of slow tests ---";

/// Top-level paths that no build reads: a change only here needs no tests. Everything else
/// outside a package (manifests, `Cargo.lock`, `.config/`, `assets/`, `clippy.toml`, …) tests all.
// Not `packaging/`: engine builds in `packaging/update-key.pub`.
const NOT_BUILT: &[&str] = &["docs/", ".github/", "scripts/", "plan/", "log/", "dev_assets/"];

pub fn nextest_available(root: &Path) -> bool {
    cargo(root).args(["nextest", "--version"]).output().is_ok_and(|out| out.status.success())
}

/// The full test step: every test, then the doctests (nextest does not run doctests). Falls back
/// to `cargo test` when nextest is not installed.
pub fn full(root: &Path) -> Result<(), String> {
    if !nextest_available(root) {
        eprintln!("note: cargo-nextest is not installed, so tests run one binary at a time with `cargo test`.");
        eprintln!("      `cargo install cargo-nextest --locked` makes this step several times faster.");
        let mut c = cargo(root);
        c.args(["test", "--workspace", "--features", PROVIDER_FEATURES]);
        return run(c, "cargo test --workspace");
    }
    let mut c = cargo(root);
    c.args(["nextest", "run", "--workspace", "--features", PROVIDER_FEATURES]);
    run(c, "cargo nextest run --workspace")?;
    let mut doc = cargo(root);
    doc.args(["test", "--doc", "--workspace", "--features", PROVIDER_FEATURES]);
    run(doc, "cargo test --doc --workspace")
}

/// The quick test step: the affected packages' tests, without the slow ones and the doctests.
pub fn quick(root: &Path, base: &str) -> Result<(), String> {
    if !nextest_available(root) {
        return Err("`--quick` needs cargo-nextest: `cargo install cargo-nextest --locked`. `cargo xtask ci` works without it.".into());
    }
    let filter = match affected(root, base)? {
        Affected::All(reason) => {
            eprintln!("quick: testing every package ({reason})");
            None
        }
        Affected::Packages(packages) if packages.is_empty() => {
            eprintln!("quick: no package changed since {base}, so no tests to run");
            return Ok(());
        }
        Affected::Packages(packages) => {
            eprintln!("quick: testing {} and the packages that depend on them", packages.iter().cloned().collect::<Vec<_>>().join(", "));
            Some(packages.iter().map(|p| format!("rdeps(={p})")).collect::<Vec<_>>().join(" | "))
        }
    };
    let mut c = cargo(root);
    c.args(["nextest", "run", "--workspace", "--features", PROVIDER_FEATURES, "--profile", "quick", "--no-tests=pass"]);
    if let Some(filter) = &filter {
        c.args(["-E", filter]);
    }
    run(c, "cargo nextest run --profile quick (slow tests and doctests left out)")
}

#[derive(Debug, PartialEq)]
pub enum Affected {
    /// Test everything, and why.
    All(String),
    /// The packages whose own files changed; nextest's `rdeps()` adds their dependents.
    Packages(BTreeSet<String>),
}

fn affected(root: &Path, base: &str) -> Result<Affected, String> {
    let merge_base = match git(root, &["merge-base", "HEAD", base]) {
        Ok(out) => String::from_utf8_lossy(&out).trim().to_owned(),
        Err(e) => return Ok(Affected::All(format!("no merge base with {base}: {e}"))),
    };
    // Committed, staged and unstaged changes against the merge base, plus new untracked files.
    // Without rename detection a move lists both its old and new path.
    let mut changed = split_paths(&git(root, &["diff", "--name-only", "--no-renames", "-z", &merge_base])?);
    changed.extend(split_paths(&git(root, &["ls-files", "--others", "--exclude-standard", "-z"])?));
    let meta = metadata(root)?;
    let workspace = meta["workspace_root"].as_str().ok_or("cargo metadata omitted workspace_root")?;
    let mut packages = Vec::new();
    for package in meta["packages"].as_array().ok_or("cargo metadata: no packages array")? {
        let name = package["name"].as_str().ok_or("package without name")?;
        let manifest = package["manifest_path"].as_str().ok_or("package without manifest_path")?;
        let dir = Path::new(manifest).parent().and_then(|dir| dir.strip_prefix(workspace).ok()).ok_or("package outside the workspace root")?;
        // Git reports `/`-separated paths on every platform.
        let dir = dir.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/");
        packages.push((name.to_owned(), dir));
    }
    Ok(classify(&changed, &packages))
}

/// Map changed paths (relative to the workspace root) to the packages that own them.
pub fn classify(changed: &[String], packages: &[(String, String)]) -> Affected {
    let mut out = BTreeSet::new();
    for path in changed {
        let owner = packages
            .iter()
            .filter(|(_, dir)| !dir.is_empty() && path.strip_prefix(dir.as_str()).is_some_and(|rest| rest.starts_with('/')))
            .max_by_key(|(_, dir)| dir.len());
        if let Some((name, _)) = owner {
            out.insert(name.clone());
        } else if !(NOT_BUILT.iter().any(|prefix| path.starts_with(prefix)) || (!path.contains('/') && path.ends_with(".md"))) {
            return Affected::All(format!("{path} is outside every package"));
        }
    }
    Affected::Packages(out)
}

fn split_paths(raw: &[u8]) -> Vec<String> {
    raw.split(|b| *b == 0).filter(|p| !p.is_empty()).map(|p| String::from_utf8_lossy(p).into_owned()).collect()
}

fn git(root: &Path, args: &[&str]) -> Result<Vec<u8>, String> {
    let out = Command::new("git").current_dir(root).args(args).output().map_err(|e| format!("git {}: {e}", args.join(" ")))?;
    if out.status.success() { Ok(out.stdout) } else { Err(format!("git {}: {}", args.join(" "), String::from_utf8_lossy(&out.stderr).trim())) }
}

/// `cargo xtask slow-tests [--threshold SECS]`: run every test once under nextest, then rewrite the
/// generated block of `.config/nextest.toml` with the tests that took at least the threshold.
pub fn slow_tests(root: &Path, args: &[&str]) -> Result<(), String> {
    let threshold = match args {
        [] => 5.0,
        ["--threshold", secs] => secs.parse::<f64>().ok().filter(|s| s.is_finite() && *s > 0.0).ok_or(format!("bad threshold `{secs}`: want seconds > 0"))?,
        _ => return Err("usage: cargo xtask slow-tests [--threshold SECS]".into()),
    };
    if !nextest_available(root) {
        return Err("slow-tests needs cargo-nextest: `cargo install cargo-nextest --locked`".into());
    }
    let path = root.join(NEXTEST_CONFIG);
    let config = std::fs::read_to_string(&path).map_err(|e| format!("read {NEXTEST_CONFIG}: {e}"))?;
    // Empty the block first: an entry naming a package that no longer exists stops nextest from
    // running at all, and a stale list must never block its own regeneration.
    std::fs::write(&path, replace_block(&config, &render_block(&[], threshold))?).map_err(|e| format!("write {NEXTEST_CONFIG}: {e}"))?;
    let mut c = cargo(root);
    c.args(["nextest", "run", "--workspace", "--features", PROVIDER_FEATURES, "--profile", "slow-tests", "--no-fail-fast"]);
    if let Err(e) = run(c, "cargo nextest run --workspace --profile slow-tests") {
        // A failing test leaves the old list in place rather than none at all.
        std::fs::write(&path, &config).map_err(|w| format!("{e}; restoring {NEXTEST_CONFIG} also failed: {w}"))?;
        return Err(e);
    }
    let target = metadata(root)?["target_directory"].as_str().ok_or("cargo metadata omitted target_directory")?.to_owned();
    let junit = Path::new(&target).join("nextest/slow-tests/junit.xml");
    let xml = std::fs::read_to_string(&junit).map_err(|e| format!("read {}: {e}", junit.display()))?;
    let mut slow: Vec<Timed> = parse_junit(&xml).into_iter().filter(|t| t.secs >= threshold).collect();
    slow.sort_by(|a, b| b.secs.total_cmp(&a.secs).then_with(|| a.package.cmp(&b.package)).then_with(|| a.test.cmp(&b.test)));
    let updated = replace_block(&config, &render_block(&slow, threshold))?;
    std::fs::write(&path, updated).map_err(|e| format!("write {NEXTEST_CONFIG}: {e}"))?;
    println!("{} test(s) took at least {threshold}s; updated {NEXTEST_CONFIG}", slow.len());
    Ok(())
}

#[derive(Debug, PartialEq)]
pub struct Timed {
    pub package: String,
    pub test: String,
    pub secs: f64,
}

/// Every `<testcase>` in nextest's JUnit report: its package (from the binary id, `classname`), name
/// and time. Entries name the package, not the binary: test files move between binaries, and a
/// `binary_id` that matches nothing is an error that stops every run.
pub fn parse_junit(xml: &str) -> Vec<Timed> {
    let mut out = Vec::new();
    for case in xml.split("<testcase ").skip(1) {
        // Splitting took the space before the first attribute; put it back for `attr`.
        let Some(tag) = case.split('>').next().map(|tag| format!(" {tag}")) else { continue };
        let (Some(test), Some(binary), Some(secs)) = (attr(&tag, "name"), attr(&tag, "classname"), attr(&tag, "time").and_then(|t| t.parse::<f64>().ok()))
        else {
            continue;
        };
        // Only plain Rust paths go into a filterset unquoted.
        let plain = |s: &str| !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | ':' | '-'));
        let package = binary.split("::").next().unwrap_or_default().to_owned();
        if plain(&test) && plain(&package) && secs.is_finite() {
            out.push(Timed { package, test, secs });
        }
    }
    out
}

fn attr(tag: &str, name: &str) -> Option<String> {
    let needle = format!(" {name}=\"");
    let start = tag.find(&needle)?.checked_add(needle.len())?;
    let rest = tag.get(start..)?;
    let value = rest.get(..rest.find('"')?)?;
    Some(value.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"").replace("&apos;", "'").replace("&amp;", "&"))
}

/// Slow tests start first, longest tier first, so a long one never finishes last; nextest
/// priorities run from -100 to 100.
const TIERS: &[(f64, i32)] = &[(120.0, 100), (60.0, 90), (30.0, 80), (15.0, 70), (0.0, 60)];

pub fn render_block(slow: &[Timed], threshold: f64) -> String {
    let matcher = |t: &Timed| format!("(package(={}) & test(={}))", t.package, t.test);
    let mut out = format!(
        "{BEGIN}\n# {} test(s) took at least {threshold}s in a full parallel run. Every profile starts them first, so\n\
         # the longest don't finish last; the `quick` profile (`cargo xtask ci --quick`) leaves them out.\n",
        slow.len()
    );
    let mut floor = f64::INFINITY;
    for &(min, priority) in TIERS {
        let tier: Vec<String> = slow.iter().filter(|t| t.secs >= min && t.secs < floor).map(matcher).collect();
        floor = min;
        if !tier.is_empty() {
            out.push_str(&format!("\n[[profile.default.overrides]]\nfilter = '''\n    {}\n'''\npriority = {priority}\n", tier.join("\n  | ")));
        }
    }
    let quick = if slow.is_empty() { "all()".to_owned() } else { format!("not (\n    {}\n)", slow.iter().map(matcher).collect::<Vec<_>>().join("\n  | ")) };
    out.push_str(&format!("\n[profile.quick]\ndefault-filter = '''\n{quick}\n'''\n{END}\n"));
    out
}

pub fn replace_block(config: &str, block: &str) -> Result<String, String> {
    let start = config.find(BEGIN).ok_or(format!("{NEXTEST_CONFIG} has no `{BEGIN}` line"))?;
    let end = config.find(END).filter(|end| *end > start).ok_or(format!("{NEXTEST_CONFIG} has no `{END}` line after the start"))?;
    let after = end.checked_add(END.len()).and_then(|i| config.get(i..)).ok_or("bad block end")?;
    let before = config.get(..start).ok_or("bad block start")?;
    Ok(format!("{before}{}{}", block.trim_end_matches('\n'), after))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn packages() -> Vec<(String, String)> {
        [
            ("nodecraft-engine", "crates/engine"),
            ("nodecraft-graph", "crates/graph"),
            ("nodecraft", "apps/nodecraft"),
            ("nodecraft-cli", "apps/nodecraft-cli"),
            ("xtask", "xtask"),
        ]
        .iter()
        .map(|(n, d)| (n.to_string(), d.to_string()))
        .collect()
    }

    fn classify_paths(paths: &[&str]) -> Affected {
        classify(&paths.iter().map(|p| p.to_string()).collect::<Vec<_>>(), &packages())
    }

    fn some(names: &[&str]) -> Affected {
        Affected::Packages(names.iter().map(|n| n.to_string()).collect())
    }

    #[test]
    fn files_map_to_the_package_that_owns_them() {
        assert_eq!(
            classify_paths(&["crates/engine/src/lib.rs", "crates/engine/tests/a.rs", "apps/nodecraft-cli/src/main.rs"]),
            some(&["nodecraft-cli", "nodecraft-engine"])
        );
        // A sibling directory sharing a name prefix is not inside the shorter one.
        assert_eq!(classify_paths(&["apps/nodecraft-cli/Cargo.toml"]), some(&["nodecraft-cli"]));
        assert_eq!(classify_paths(&["xtask/src/main.rs"]), some(&["xtask"]));
    }

    #[test]
    fn prose_and_tooling_need_no_tests() {
        assert_eq!(classify_paths(&["docs/development.md", "AGENTS.md", ".github/workflows/ci.yml", "scripts/claim/claim.js"]), some(&[]));
        assert_eq!(classify_paths(&[]), some(&[]));
    }

    #[test]
    fn anything_else_outside_a_package_tests_everything() {
        for path in [
            "Cargo.toml",
            "Cargo.lock",
            ".config/nextest.toml",
            "assets/catalog/x.toml",
            "clippy.toml",
            "packaging/update-key.pub",
            "crates/new/lib.rs",
            "crates/README.txt",
        ] {
            assert!(matches!(classify_paths(&["crates/engine/src/lib.rs", path]), Affected::All(reason) if reason.contains(path)), "{path}");
        }
    }

    #[test]
    fn junit_testcases_parse_and_odd_names_are_dropped() {
        let xml = r#"<testsuites><testsuite name="nodecraft-engine">
<testcase name="jobs::tests::slow" classname="nodecraft-engine" timestamp="t" time="407.5"></testcase>
<testcase name="lazy_assets147::fast" classname="nodecraft-engine::it" time="0.01"/>
<testcase name="weird name(1)" classname="x" time="9"/>
<testcase name="no_time" classname="x"/>
</testsuite></testsuites>"#;
        let parsed = parse_junit(xml);
        assert_eq!(
            parsed,
            vec![
                Timed { package: "nodecraft-engine".into(), test: "jobs::tests::slow".into(), secs: 407.5 },
                Timed { package: "nodecraft-engine".into(), test: "lazy_assets147::fast".into(), secs: 0.01 },
            ]
        );
    }

    #[test]
    fn block_tiers_by_duration_and_round_trips() {
        let slow = vec![Timed { package: "a".into(), test: "t1".into(), secs: 200.0 }, Timed { package: "b".into(), test: "m::t2".into(), secs: 7.0 }];
        let block = render_block(&slow, 5.0);
        assert!(block.contains("(package(=a) & test(=t1))\n'''\npriority = 100"), "{block}");
        assert!(block.contains("(package(=b) & test(=m::t2))\n'''\npriority = 60"), "{block}");
        assert!(block.contains("[profile.quick]\ndefault-filter = '''\nnot (\n    (package(=a) & test(=t1))\n  | (package(=b) & test(=m::t2))\n)"), "{block}");
        let config = format!("[profile.ci]\nfail-fast = true\n\n{BEGIN}\nold\n{END}\n\n# tail\n");
        let once = replace_block(&config, &block).unwrap();
        assert_eq!(replace_block(&once, &block).unwrap(), once);
        assert!(once.starts_with("[profile.ci]\nfail-fast = true\n\n") && once.ends_with(&format!("{END}\n\n# tail\n")) && !once.contains("old"));
        assert!(render_block(&[], 5.0).contains("default-filter = '''\nall()\n'''"));
        assert!(replace_block("no markers", &block).is_err());
    }
}
